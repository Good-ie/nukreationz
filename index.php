        // Function to show the popup with animation
        function showPopup() {
            var popup = document.getElementById("popup");
            popup.style.display = "block";
            popup.classList.add("fadeIn");
        }

        // Close the popup with animation when the close link is clicked
        var closeLink = document.getElementById("close-popup");
        closeLink.addEventListener("click", function(event) {
            event.preventDefault();
            var popup = document.getElementById("popup");
            popup.classList.remove("fadeIn");
            popup.classList.add("fadeOut");
            setTimeout(function() {
                popup.style.display = "none";
                popup.classList.remove("fadeOut");
            }, 500);
        });
    });

    // Handle form submission
    var form = document.querySelector("form");
    form.addEventListener("submit", function(event) {
        event.preventDefault();

        // Get the email value from the input field
        var emailInput = document.querySelector("input[type='email']");
        var nameInput = document.querySelector("input[type='text']");
        var email = emailInput.value;
        var name = nameInput.value;

        // Make an AJAX request to the PHP script
        var xhr = new XMLHttpRequest();
        xhr.open("POST", "save_email.php", true);
        xhr.setRequestHeader("Content-type", "application/x-www-form-urlencoded");
        xhr.onreadystatechange = function() {
            if (xhr.readyState === 4 && xhr.status === 200) {
                // Handle the response from the PHP script
                var response = JSON.parse(xhr.responseText);
                var responseMessage = document.getElementById("response-message");
                if (response.success) {
                    // Display a success message
                    responseMessage.textContent = "Email successfully saved!";
                    responseMessage.style.color = "green";
                    setTimeout(function() {
                        popup.style.display = "none";
                        popup.classList.remove("fadeOut");
                    }, 2000);

                    // Clear the input field
                    emailInput.value = "";
                } else {
                    // Display an error message
                    responseMessage.textContent = "Thanks " + response.message;
                    responseMessage.style.color = "green";
                    setTimeout(function() {
                        popup.style.display = "none";
                        popup.classList.remove("fadeOut");
                    }, 2000);
                }
            }
        };
        var data = "email=" + encodeURIComponent(email) + "&name=" + encodeURIComponent(name);
        xhr.send(data);
    });
